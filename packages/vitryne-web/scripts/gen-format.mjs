// Generates the app's view of the file format from docs/format/schema/ (the source of truth):
//   src/format/schema.gen.ts      TypeScript types of each entity (json-schema-to-typescript)
//   src/format/validators.gen.js  precompiled validators (Ajv standalone, no eval at run time)
// usage: node scripts/gen-format.mjs [--check]   --check: fail if the files are stale (make check)
//
// Unknown members: the schemas close every object (unevaluatedProperties: false), but readers
// keep what they don't know (file-format.md) and Rust validates the whole document after every edit.
// So the app's validators drop that one keyword: they check what a command can get wrong
// (types, ranges, required members) and let a newer file's extra members through.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const root = resolve(import.meta.dirname, "..");
const schemaDir = resolve(root, "../../docs/format/schema");
const ENTITIES = {
  project: "Project",
  garment: "Garment",
  fabric: "Fabric",
  appearance: "Appearance",
  avatar: "Avatar",
  view: "View",
};
const HEADER = (what) =>
  `// SPDX-License-Identifier: AGPL-3.0-or-later\n// GENERATED by scripts/gen-format.mjs from docs/format/schema/: ${what}. Do not edit.\n`;

const schemas = Object.fromEntries(
  readdirSync(schemaDir)
    .filter((f) => f.endsWith(".schema.json"))
    .sort()
    .map((f) => [f, JSON.parse(readFileSync(resolve(schemaDir, f), "utf8"))]),
);

function open(v) {
  if (Array.isArray(v)) return v.map(open);
  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v)
        .filter(([k, x]) => !(k === "unevaluatedProperties" && x === false))
        .map(([k, x]) => [k, open(x)]),
    );
  }
  return v;
}

// ---- types ---------------------------------------------------------------------------------
// json-schema-to-typescript drops a `required` that sits next to a `$ref` (garment's
// outlineNode: a node whose edge is required), so such local refs are inlined first.
function inlineRefsWithRequired(schema) {
  const defs = schema.$defs ?? {};
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (!v || typeof v !== "object") return v;
    const out = Object.fromEntries(
      Object.entries(v).map(([k, x]) => [k, walk(x)]),
    );
    const m =
      typeof out.$ref === "string" &&
      out.required &&
      /^#\/\$defs\/(\w+)$/.exec(out.$ref);
    if (m && defs[m[1]]) {
      const { $ref: _ref, required, ...rest } = out;
      const target = walk(defs[m[1]]);
      return {
        ...target,
        ...rest,
        required: [...new Set([...(target.required ?? []), ...required])],
      };
    }
    return out;
  };
  return walk(schema);
}

let types = HEADER("the entities as TypeScript types");
for (const [file, name] of Object.entries(ENTITIES)) {
  const schema = inlineRefsWithRequired(
    structuredClone(schemas[`${file}.schema.json`]),
  );
  schema.title = name;
  const ts = await compile(schema, name, {
    cwd: schemaDir,
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: true,
    strictIndexSignatures: true,
    style: { singleQuote: true, printWidth: 110 },
  });
  types += `\n// ---- ${file}.schema.json\n${ts}`;
}
// The same definitions appear once per entity file that references them: keep the first.
const seen = new Set();
types = types.replace(
  /(?:\/\*\*[\s\S]*?\*\/\n)?export (?:interface|type) (\w+)[\s\S]*?\n(?=(?:\/\*\*|export |\/\/ ----|$))/g,
  (block, name) => {
    if (seen.has(name)) return "";
    seen.add(name);
    return block;
  },
);

// Free-form objects (engine settings, extension data) as records rather than `{}`.
types = types
  .replace(/engine\?: \{\};/g, "engine?: { [k: string]: unknown };")
  .replace(/\[k: string\]: \{\} \| undefined;/g, "[k: string]: unknown;");

// ---- validators ----------------------------------------------------------------------------
const ajv = new Ajv2020({
  code: { source: true, esm: true, lines: true },
  allErrors: true,
  strict: false,
});
for (const s of Object.values(schemas)) ajv.addSchema(open(s));
const refs = Object.fromEntries(
  Object.keys(ENTITIES).map((f) => [f, schemas[`${f}.schema.json`].$id]),
);
// Ajv's ESM output still `require`s its few runtime helpers (deep equality for uniqueItems):
// turn those into imports.
let code = standalone(ajv, refs);
const imports = [];
code = code.replace(
  /const (\w+) = require\("([^"]+)"\)\.default;/g,
  (_, name, mod) => {
    imports.push(
      `import ${name}_module from '${mod}.js';\nconst ${name} = ${name}_module.default ?? ${name}_module;`,
    );
    return "";
  },
);
if (/\brequire\(/.test(code))
  throw new Error("validators.gen.js: an unhandled require() is left");
const validators =
  HEADER("Ajv standalone validators, one per entity") +
  imports.join("\n") +
  "\n" +
  code;

const declarations =
  HEADER("declarations of validators.gen.js") +
  `type Validator = ((value: unknown) => boolean) & { errors?: { instancePath: string; message?: string }[] | null };\n` +
  Object.keys(ENTITIES)
    .map((k) => `export declare const ${k}: Validator;\n`)
    .join("");
const out = {
  "src/format/schema.gen.ts": types,
  "src/format/validators.gen.js": validators,
  "src/format/validators.gen.d.ts": declarations,
};
const check = process.argv.includes("--check");
let stale = [];
for (const [p, text] of Object.entries(out)) {
  const path = resolve(root, p);
  let old = null;
  try {
    old = readFileSync(path, "utf8");
  } catch {}
  if (old === text) continue;
  if (check) stale.push(p);
  else writeFileSync(path, text);
}
if (stale.length) {
  console.error(`stale: ${stale.join(", ")} (run: pnpm run gen:format)`);
  process.exit(1);
}
console.log(
  check
    ? "format types and validators are up to date"
    : "wrote " + Object.keys(out).join(", "),
);
