"""Extract the 'body' group of the MakeHuman base mesh (hm08) and convert it to metres with
feet at y = 0, triangulating its quads.
usage: python3 convert.py base.obj makehuman_body_m.obj
Source: https://github.com/makehumancommunity/makehuman  makehuman/data/3dobjs/base.obj (CC0)."""
import sys

src, dst = sys.argv[1], sys.argv[2]
vs, faces, group = [], [], None
for line in open(src):
    if line.startswith('v '):
        vs.append(tuple(map(float, line.split()[1:4])))
    elif line.startswith('g '):
        group = line.split()[1]
    elif line.startswith('f ') and group == 'body':
        faces.append([int(t.split('/')[0]) - 1 for t in line.split()[1:]])
used = sorted({i for f in faces for i in f})
remap = {old: new for new, old in enumerate(used)}
ymin = min(vs[i][1] for i in used)
with open(dst, 'w') as out:
    out.write('# MakeHuman base mesh hm08, "body" group only, metres, feet at y=0, Y up, facing +Z.\n')
    out.write('# Released CC0 by its copyright holders (Data Collection AB, Joel Palmius, Jonas Hauquier), 2020.\n')
    out.write('# Generated by assets/body/convert.py from makehuman/data/3dobjs/base.obj\n')
    for i in used:
        x, y, z = vs[i]
        out.write(f'v {x * 0.1:.6f} {(y - ymin) * 0.1:.6f} {z * 0.1:.6f}\n')
    for f in faces:
        f = [remap[i] + 1 for i in f]
        for k in range(1, len(f) - 1):
            out.write(f'f {f[0]} {f[k]} {f[k + 1]}\n')
print(f'{len(used)} vertices, {sum(len(f) - 2 for f in faces)} triangles')
